def get_category_config(name: str) -> dict | None:
    """获取某个类别的配置（兼容中文名称和内部 key）"""
    key = CATEGORY_NAMES.get(name, name)
    return CATEGORIES.get(key)


def get_body_parts_for_category(name: str) -> list[str]:
    cfg = get_category_config(name)
    return cfg["body_parts"] if cfg else BODY_PARTS


